/**
 * Third-party license manifest generator.
 *
 * Collects name/version/license/author/homepage for every production
 * dependency shipped with the app — including the Pi SDK's own bundled
 * dependencies (npm-shrinkwrap installs them under the SDK's node_modules) —
 * and writes resources/THIRD-PARTY-LICENSES.md. The file ships inside the
 * release because resources/ is copied via extraResources.
 *
 * Usage: node scripts/generate-licenses.mjs
 */
import { createRequire } from 'node:module'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const req = createRequire(join(root, 'package.json'))

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'))

/** Production deps + the desktop's own runtime requirements, recursively. */
function* walkDependencies(name, seen = new Set()) {
  if (seen.has(name)) return
  seen.add(name)
  let dir
  try {
    // Resolve the package main, then climb to its package.json. ESM-only
    // packages with restricted exports fail require() — resolve their file
    // path directly under node_modules instead.
    dir = resolve(req.resolve(name), '..')
    while (dir && !existsSync(join(dir, 'package.json'))) {
      const parent = resolve(dir, '..')
      if (parent === dir) break
      dir = parent
    }
  } catch {
    dir = join(root, 'node_modules', name)
  }
  if (!dir || !existsSync(join(dir, 'package.json'))) return
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf-8'))
  yield { name, manifest, dir }
  for (const dep of Object.keys(manifest.dependencies ?? {})) {
    yield* walkDependencies(dep, seen)
  }
}

// Start from the app's production dependencies, then walk the SDK's whole
// shrinkwrapped tree so nothing shipped goes unlisted.
const roots = Object.keys(pkg.dependencies ?? {})
roots.push('@earendil-works/pi-coding-agent')

const rows = new Map()
for (const rootDep of roots) {
  for (const { name, manifest } of walkDependencies(rootDep)) {
    if (rows.has(name)) continue
    rows.set(name, {
      name,
      version: manifest.version ?? 'unknown',
      license:
        typeof manifest.license === 'string'
          ? manifest.license
          : Array.isArray(manifest.licenses)
            ? manifest.licenses.join(', ')
            : 'unknown',
      author:
        typeof manifest.author === 'string'
          ? manifest.author
          : manifest.author?.name ?? '',
      homepage: manifest.homepage ?? manifest.repository?.url ?? '',
    })
  }
}

const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name))

const lines = [
  '# Third-Party Licenses',
  '',
  'Pi Desktop ships with the Pi coding agent SDK and its runtime dependencies.',
  'This manifest lists the packages distributed inside the application bundle',
  'together with their declared licenses. It does not cover packages the user',
  'installs later through Pi package management.',
  '',
  `${sorted.length} packages, generated by scripts/generate-licenses.mjs.`,
  '',
  '| Package | Version | License | Author / Homepage |',
  '|---------|---------|---------|-------------------|',
]

for (const row of sorted) {
  const author = [row.author, row.homepage].filter(Boolean).join(' — ')
  lines.push(
    `| ${row.name} | ${row.version} | ${row.license} | ${author.replace(/\|/g, '\\|')} |`,
  )
}

const outPath = join(root, 'resources', 'THIRD-PARTY-LICENSES.md')
writeFileSync(outPath, lines.join('\n') + '\n', 'utf-8')
console.log(`[generate-licenses] wrote ${sorted.length} packages to ${outPath}`)
